--
-- null 은 "한 번도 고치지 않았다" 는 뜻이다. 기존 댓글을 created_at 으로 채우지 않는 것은
-- 그렇게 하면 전부 '수정됨' 으로 보이기 때문이다.
alter table comments add column updated_at timestamp(6);
