-- 예상 소요 시간(분).
--
-- 통계의 '계획 대비 실행률' 은 계획 시간을 end_time - start_time 으로만 구했다.
-- 그런데 주 입력 경로인 '한 줄 추가' 는 시각을 받지 않는다 - 제목과 분류뿐이다.
-- 그래서 대부분의 계획은 계획 시간이 0이었고, 화면은 0이면 실행률을 조용히 감췄다.
-- 기능이 없어진 줄도 모르고 쓰는 상태였다.
--
-- "언제 할까"(시각)와 "얼마나 걸릴까"(소요 시간)는 다른 값이다. 사람은 대개 뒤의 것을 먼저 안다.
-- 시각이 둘 다 있으면 그쪽이 더 정확하므로 그것을 쓰고, 없을 때 이 값을 쓴다(Plan#getStudyMinutes).
--
-- null 을 허용하는 이유: 0 은 "0분 걸린다" 로도 읽히지만 null 은 "적지 않았다" 하나로만 읽힌다.
-- 기존 행은 전부 null - 실제로 아무도 적은 적이 없다.
alter table plan add column estimated_minutes integer;
